#!/usr/bin/env python3
"""Generate Sanity's MuJoCo XML from its authoritative URDF and existing meshes."""
from pathlib import Path
import xml.etree.ElementTree as ET

import numpy as np
from scipy.spatial.transform import Rotation

ROOT = Path(__file__).resolve().parents[1]


def numbers(values):
    return ' '.join(f'{v:.12g}' for v in values)


def origin(element):
    item = element.find('origin')
    attrs = item.attrib if item is not None else {}
    pos = np.fromstring(attrs.get('xyz', '0 0 0'), sep=' ')
    rotation = Rotation.from_euler('xyz', np.fromstring(attrs.get('rpy', '0 0 0'), sep=' '))
    return pos, rotation


def build(source=ROOT / 'models/sanity.urdf'):
    urdf = ET.parse(source).getroot()
    base = urdf.find("link[@name='base_link']")
    assert base is not None
    links = urdf.findall('link')
    joints = urdf.findall('joint')
    assert len(links) == 5 and len(joints) == 4
    for link in links:
        if link is not base:
            assert len(link.findall('visual')) == len(link.findall('collision')) == 0
            assert float(link.find('inertial/mass').get('value')) == 0
            assert all(float(v) == 0 for v in link.find('inertial/inertia').attrib.values())

    root = ET.Element('mujoco', model='sanity')
    root.append(ET.Comment('Generated by tools/build_mjcf.py from sanity.urdf. SI units.'))
    ET.SubElement(root, 'compiler', angle='radian', inertiafromgeom='false', alignfree='false')
    ET.SubElement(root, 'option', timestep='0.002', gravity='0 0 -9.80665', integrator='implicitfast')
    ET.SubElement(root, 'statistic', center='0 0 0', extent='0.16')
    asset = ET.SubElement(root, 'asset')
    world = ET.SubElement(root, 'worldbody')
    body = ET.SubElement(world, 'body', name='base_link')
    ET.SubElement(body, 'freejoint', name='floating_base')

    # Rotate the URDF tensor into base axes; never infer inertia from mesh density.
    inertial = base.find('inertial')
    pos, rotation = origin(inertial)
    a = {k: float(v) for k, v in inertial.find('inertia').attrib.items()}
    tensor = np.array([[a['ixx'], a['ixy'], a['ixz']],
                       [a['ixy'], a['iyy'], a['iyz']],
                       [a['ixz'], a['iyz'], a['izz']]])
    tensor = rotation.as_matrix() @ tensor @ rotation.as_matrix().T
    ET.SubElement(body, 'inertial', pos=numbers(pos), mass=inertial.find('mass').get('value'),
                  fullinertia=numbers(tensor[[0, 1, 2, 0, 0, 1], [0, 1, 2, 1, 2, 2]]))

    for kind in ['visual', 'collision']:
        for i, shape in enumerate(base.findall(kind)):
            mesh = shape.find('geometry/mesh')
            assert mesh is not None, 'Only the existing mesh geometry is supported.'
            name = f'{kind}_{i}'
            ET.SubElement(asset, 'mesh', name=name, file=mesh.get('filename'),
                          scale=mesh.get('scale', '1 1 1'))
            pos, rotation = origin(shape)
            attrs = dict(name=name, type='mesh', mesh=name, pos=numbers(pos),
                         quat=numbers(rotation.as_quat(scalar_first=True)), mass='0')
            if kind == 'visual':
                color = shape.find('material/color')
                assert color is not None
                ET.SubElement(asset, 'material', name=name, rgba=color.get('rgba'))
                attrs.update(material=name, contype='0', conaffinity='0', group='1')
            else:
                attrs.update(rgba='0.4 0.7 1 0.2', group='3', contype='1', conaffinity='1')
            ET.SubElement(body, 'geom', **attrs)

    names = []
    for joint in joints:
        assert joint.get('type') == 'fixed' and joint.find('parent').get('link') == 'base_link'
        name = joint.find('child').get('link')
        names.append(name)
        pos, rotation = origin(joint)
        ET.SubElement(body, 'site', name=name, pos=numbers(pos),
                      quat=numbers(rotation.as_quat(scalar_first=True)),
                      size='0.001', rgba='0 0 0 0', group='4')

    actuators = ET.SubElement(root, 'actuator')
    actuators.append(ET.Comment('Inputs 0:4: rotor-frame +Z thrust in N. Use nonnegative forces.'))
    for name in names:
        ET.SubElement(actuators, 'motor', name=name + '_thrust', site=name,
                      gear='0 0 1 0 0 0', ctrllimited='false')
    actuators.append(ET.Comment('Inputs 4:8: signed reaction moments on the body in Nm about rotor +Z.'))
    actuators.append(ET.Comment('Torque coefficient, rotation directions and FC mapping are unknown; no automatic coupling.'))
    for name in names:
        ET.SubElement(actuators, 'motor', name=name + '_reaction_torque', site=name,
                      gear='0 0 0 0 0 1', ctrllimited='false')
    ET.indent(root, space='  ')
    return '<?xml version="1.0"?>\n' + ET.tostring(root, encoding='unicode') + '\n'


if __name__ == '__main__':
    output = ROOT / 'models/sanity.xml'
    output.write_text(build())
    print(output.relative_to(ROOT))
